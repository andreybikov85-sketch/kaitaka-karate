// Палитра клуба КАЙТАКА. Цвета задаются ТОЛЬКО здесь.
//
// Если цвет понадобился в другом модуле — добавь его сюда и импортируй.
// Как только цвета начнут появляться по месту, уровни поедут в разные стороны,
// и вернуть единый вид будет уже тяжело.
//
// Числа в формате 0xRRGGBB — three.js работает с ними напрямую.
// Те же цвета продублированы в style.css как CSS-переменные для интерфейса.

export const C = {
  // Фирменные
  kyoku:  0xc1272d,   // красный киокушинкай — эмблема, эффекты попадания
  club:   0x3f3a8c,   // индиго КАЙТАКА — знамёна, стены клуба
  gold:   0xe8b647,   // золото — пояса данов, вручение, акценты

  // Материалы
  gi:     0xf2ede2,   // кимоно
  giShade:0xc9c2b4,   // складки кимоно
  skin:   0xe8b98f,
  hair:   0x241a12,

  // Окружение
  night:  0x141824,   // тёмный фон, небо в помещении
  night2: 0x1d2333,
  tatami: 0x2f5d50,   // зелёный татами
  tatami2:0x274f44,   // второй тон татами для клетки
  wood:   0x6b5334,   // дерево пола и стоек
  wall:   0xd9cfbe    // стена додзё
};

// Тот же набор строками — для случаев, где нужен CSS-цвет.
export const CSS = Object.fromEntries(
  Object.entries(C).map(([k, v]) => [k, "#" + v.toString(16).padStart(6, "0")])
);
