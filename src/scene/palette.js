// Палитра клуба КАЙТАКА. Цвета задаются ТОЛЬКО здесь.
//
// Сняты с фотографий настоящего зала — медианой по участкам, а не на глаз.
// Поэтому если что-то смотрится не так, правится оно тут, и весь зал
// перекрашивается разом.
//
// Числа в формате 0xRRGGBB — three.js работает с ними напрямую.
// Те же цвета продублированы в style.css как CSS-переменные для интерфейса.

export const C = {
  // Фирменные
  kyoku:  0xc1272d,   // красный киокушинкай — эмблема, эффекты попадания
  club:   0x3f3a8c,   // индиго КАЙТАКА — знамёна, интерфейс
  gold:   0xe8b647,   // золото — пояса данов, вручение, акценты

  // Материалы бойцов
  gi:     0xf2ede2,   // кимоно
  giShade:0xc9c2b4,
  skin:   0xe8b98f,
  hair:   0x241a12,

  // ЗАЛ. Снято с фото.
  mat:     0x0b62cc,  // синие пазловые маты — главный цвет зала
  matDark: 0x0a4ea6,  // швы между матами
  matEdge: 0x0d6fe0,  // блик на кромке мата

  wall:    0xd6d0c6,  // светлая стена с фактурой
  wallCool:0xc3c0bb,  // стена в тени
  ceiling: 0xf4f6f8,  // белый натяжной потолок

  wood:     0x5a3f20, // тёмное дерево колонн и плинтуса
  woodLight:0x78542e, // освещённая грань колонны
  woodDark: 0x2f2418, // грань в тени

  metal:  0xe8eaec,   // радиаторы, рамы окон
  door:   0x6b4526,   // двери

  // Роспись на дальней стене
  muralSky:  0xf6c9a6,
  muralHill: 0xfca17b,
  muralSun:  0x9f121b,
  muralInk:  0x1b1b1f,

  night:  0x141824,   // тёмный фон вне зала
  night2: 0x1d2333
};

// Тот же набор строками — для случаев, где нужен CSS-цвет.
export const CSS = Object.fromEntries(
  Object.entries(C).map(([k, v]) => [k, "#" + v.toString(16).padStart(6, "0")])
);
