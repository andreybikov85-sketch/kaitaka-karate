// ДВА РЕЖИМА ДВИЖЕНИЯ.
//
// В зале не дерутся, а в бою не гуляют. Это не украшение: по тому, как
// боец передвигается, сразу видно, тренировка сейчас или поединок.
//
//   тренировка — обычная ходьба, свободно, техника отрабатывается на счёт
//   кумитэ     — боевой подшаг, короткий и осторожный, скорость ниже
//
