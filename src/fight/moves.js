// Модель движений: что за чем идёт.
//
// Это ДАННЫЕ. Новый приём добавляется записью здесь и файлом клипа
// в assets/anims/ — код трогать не нужно.
//
// Порядок важности, сверху вниз. Верхнее прерывает нижнее:
//
//   1. падение        — прерывает всё
//   2. получил удар   — прерывает всё, кроме падения
//   3. удар           — прерывает ходьбу и стойку
//   4. блок           — пока держишь кнопку
//   5. ходьба         — пока жмёшь направление
//   6. стойка         — когда ничего не происходит
//
// Связка руками: цуки → хук → колено. Каждое следующее нажатие в окне
// связки продолжает комбинацию, вне окна — начинает заново с цуки.
// Гери живёт отдельной кнопкой и в связку не входит: у ребёнка две кнопки
// удара, и вторая должна быть предсказуемой, а не зависеть от истории.

